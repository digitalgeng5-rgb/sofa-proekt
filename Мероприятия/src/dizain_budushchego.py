def P(t, s=base):
    return Paragraph(t, s)


def bullets(items, style=bullet):
    return [Paragraph(i, style, bulletText="•") for i in items]


def kv_table(rows, col1=48 * mm):
    data = [[P(k, cell_b), P(v, cell)] for k, v in rows]
    t = Table(data, colWidths=[col1, 170 * mm - col1])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.5, LINE),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


def grid_table(header, rows, widths):
    data = [[P(h, cell_b) for h in header]]
    data += [[P(c, cell) for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.5, LINE),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
    ]))
    return t


def letter_box(paras):
    out = [Spacer(1, 6)]
    for i, p in enumerate(paras):
        out.append(p)
        if i < len(paras) - 1:
            out.append(Spacer(1, 10))
    out.append(Spacer(1, 8))
    return out


